#!/bin/bash
# Migration Script: Update submodules to use reusable workflows
# This script creates simplified CI workflows that call the reusable ones from conxian-business

set -e

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
WORKFLOWS_DIR="$REPO_ROOT/.github/workflows/reusable"

echo "=============================================="
echo "Migrating Submodules to Reusable Workflows"
echo "=============================================="
echo ""

# Define migration templates for each repo type
create_rust_ci() {
    local repo_path="$1"
    local repo_name=$(basename "$repo_path")
    
    cat > "$repo_path/.github/workflows/ci.yml" << 'EOF'
# Simplified Rust CI - calls reusable workflows from conxian-business
# Generated by migration script

name: CI

on:
  push:
    branches: [main, staged, dev]
    paths-ignore:
      - '**.md'
      - 'docs/**'
  pull_request:
    branches: [main, staged, dev]
    paths-ignore:
      - '**.md'
      - 'docs/**'
  workflow_dispatch:

concurrency:
  group: ${{ github.workflow }}-${{ github.ref }}
  cancel-in-progress: true

jobs:
  ci:
    name: Rust CI
    uses: Conxian/conxian-business/.github/workflows/reusable/rust-ci.yml@main
    with:
      rust_version: "1.96.0"

  dependency-review:
    name: Dependency Review
    uses: Conxian/conxian-business/.github/workflows/reusable/dependency-review.yml@main

  secret-scan:
    name: Secret Scan
    uses: Conxian/conxian-business/.github/workflows/reusable/secret-scan.yml@main
EOF
    
    echo "✅ Created CI for $repo_name"
}

